let application, page, server, dataDir, endpoint, repoDir, requests = [];
test.beforeAll(async () => {
  dataDir = await mkdtemp(path.join(os.tmpdir(), 'benjamin-test-'));
  repoDir = path.join(dataDir, 'workspace');
  await mkdir(repoDir);
  await execFile('git', ['init', '-b', 'feature/benjamin'], { cwd: repoDir });
  server = createServer((req, res) => {
    let body = ''; req.on('data', chunk => body += chunk); req.on('end', () => {
      requests.push(JSON.parse(body));
      res.writeHead(200, { 'Content-Type': 'text/event-stream' });
      const reply = 'Here is a safe command to check your directory:\n\n```sh\npwd\n```\n\nThis prints the current working directory.';
      res.write('data: ' + JSON.stringify({ choices: [{ delta: { content: reply.slice(0, 20) } }] }) + '\n\n');
      setTimeout(() => res.end('data: ' + JSON.stringify({ choices: [{ delta: { content: reply.slice(20) } }] }) + '\n\ndata: [DONE]\n\n'), 150);
    });
  });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve)); endpoint = `http://127.0.0.1:${server.address().port}/v1`;
  const appEnv = { ...process.env, BENJAMIN_TEST_DATA: dataDir };
  delete appEnv.NO_COLOR; delete appEnv.FORCE_COLOR;
  application = await electron.launch({ ...(process.env.BENJAMIN_EXECUTABLE ? { executablePath: process.env.BENJAMIN_EXECUTABLE, args: [] } : { args: ['.'] }), env: appEnv });
  page = await application.firstWindow();
});
test.afterAll(async () => { await application?.close(); await new Promise(resolve => server?.close(resolve)); if (dataDir) await rm(dataDir, { recursive: true, force: true }); });
